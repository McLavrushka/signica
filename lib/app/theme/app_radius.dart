/// Corner radii used across the design.
abstract final class AppRadius {
  /// App icons inside the source pills.
  static const double icon = 7;

  /// Page sheet in a document preview.
  static const double sheet = 12;

  /// Squircle tiles in the header: logo and the "…" button.
  static const double tile = 15;

  /// Segmented control thumb and the "Signed" badge.
  static const double control = 20;

  /// Context menus.
  static const double menu = 34;

  /// Rounded content sheet under the header.
  static const double surface = 36;

  /// Fully rounded controls: buttons, pills, the search field.
  static const double pill = 100;
}
